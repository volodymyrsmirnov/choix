// Quit: SIGTERM in the middle of two scans (the queue runs two folder jobs
// at once) stops the app within 8 s; started again on the same data
// directory, the folders are still listed, their jobs run to ready, and a
// pick made just before the signal is still there.
//
// Playwright's webServer cannot be restarted, so this spec runs the server
// binary global-setup.ts built itself, on its own port and data directory.
import { execFileSync, spawn, type ChildProcess } from 'node:child_process'
import { copyFileSync, existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { basename, join } from 'node:path'
import { dirs, expect, Harness, hostsAway, test, type FolderView, type PickResult } from './fixtures'

const PORT = 8091
const BASE = `http://127.0.0.1:${PORT}`
const small = join(dirs.quitRoot, 'small')
const big = join(dirs.quitRoot, 'big')
/** A second big folder, generated by this spec, scanning next to `big`. */
const big2 = join(dirs.quitRoot, 'big-2')
/** The number of photos global-setup.ts generates in `big` (and this spec in `big-2`). */
const BIG_COUNT = 300

/**
 * query runs sql with the sqlite3 CLI on a copy of the database at db (with
 * its -wal and -shm files, when present) and returns the rows. Only call it
 * while no server has the database open. The copy, not the original, is
 * opened: a WAL database cannot be opened read-only once its -shm file is
 * gone (SQLite answers "unable to open database file"), and opening the
 * original read-write would create files inside the folder's .choix.
 */
function query<T>(db: string, sql: string): T[] {
  const snap = mkdtempSync(join(dirs.tmp, 'snapshot-'))
  try {
    const copy = join(snap, basename(db))
    copyFileSync(db, copy)
    for (const suffix of ['-wal', '-shm']) {
      if (existsSync(db + suffix)) {
        copyFileSync(db + suffix, copy + suffix)
      }
    }
    const out = execFileSync('sqlite3', ['-json', copy, sql], { encoding: 'utf8' })
    return out.trim() === '' ? [] : (JSON.parse(out) as T[])
  } finally {
    rmSync(snap, { recursive: true, force: true })
  }
}

interface Persisted {
  /** library.db: the folder's job marker (1: queued, running or interrupted). */
  jobPending: number
  jobKind: string
  /** <folder>/.choix/state.db: file rows, those not analyzed yet, by status. */
  rows: number
  unfinished: number
  statuses: Record<string, number>
}

/**
 * persisted reads a big folder's persisted job state: its row in the data
 * directory's library.db and its files in <root>/.choix/state.db. Files the
 * job has not discovered yet have no row; they count as unfinished like
 * rows short of `analyzed`.
 */
function persisted(folderID: string, root: string): Persisted {
  if (!/^[0-9a-f]{16}$/.test(folderID)) {
    throw new Error(`unexpected folder id ${folderID}`)
  }
  const [job] = query<{ job_pending: number; job_kind: string }>(
    join(dirs.quitData, 'library.db'),
    `SELECT job_pending, job_kind FROM folders WHERE id = '${folderID}'`,
  )
  const statuses: Record<string, number> = {}
  for (const r of query<{ scan_status: string; n: number }>(
    join(root, '.choix', 'state.db'),
    'SELECT scan_status, COUNT(*) AS n FROM files GROUP BY scan_status',
  )) {
    statuses[r.scan_status] = r.n
  }
  const rows = Object.values(statuses).reduce((a, b) => a + b, 0)
  return {
    jobPending: job?.job_pending ?? -1,
    jobKind: job?.job_kind ?? '',
    rows,
    unfinished: BIG_COUNT - (statuses.analyzed ?? 0),
    statuses,
  }
}

/** Server is one run of the server binary. */
class Server {
  readonly proc: ChildProcess
  readonly exited: Promise<{ code: number | null; signal: NodeJS.Signals | null }>
  private log = ''

  constructor() {
    this.proc = spawn(dirs.bin, [], {
      env: {
        ...process.env,
        CHOIX_DATA_DIR: dirs.quitData,
        CHOIX_E2E_ROOT: dirs.quitRoot,
        CHOIX_ASSETS_DIR: dirs.harnessDist,
        WAILS_SERVER_PORT: String(PORT),
      },
      stdio: ['ignore', 'pipe', 'pipe'],
    })
    this.proc.stdout?.on('data', (d: Buffer) => (this.log += d.toString()))
    this.proc.stderr?.on('data', (d: Buffer) => (this.log += d.toString()))
    this.exited = new Promise((resolve) => this.proc.once('exit', (code, signal) => resolve({ code, signal })))
  }

  get running(): boolean {
    return this.proc.exitCode === null && this.proc.signalCode === null
  }

  /** ready waits for /health, failing early when the process exits. */
  async ready(timeoutMs = 60_000): Promise<void> {
    const deadline = Date.now() + timeoutMs
    while (Date.now() < deadline) {
      if (!this.running) {
        throw new Error(`the server exited before it was ready:\n${this.log}`)
      }
      try {
        if ((await fetch(`${BASE}/health`)).ok) {
          return
        }
      } catch {
        // not listening yet
      }
      await new Promise((r) => setTimeout(r, 100))
    }
    throw new Error(`the server was not ready within ${timeoutMs} ms:\n${this.log}`)
  }

  /** kill makes sure the process is gone (SIGKILL when still running). */
  async kill(): Promise<void> {
    if (this.running) {
      this.proc.kill('SIGKILL')
      await this.exited
    }
  }

  output(): string {
    return this.log
  }
}

test('SIGTERM mid-scan exits within 8 s and the work resumes on restart', async ({ browser }) => {
  test.setTimeout(300_000)
  if (!existsSync(big2)) {
    execFileSync(dirs.genfolder, ['-out', big2, '-n', String(BIG_COUNT), '-cameras', '2', '-bursts', '3'])
  }
  const servers: Server[] = []
  const page = await browser.newPage()
  const requests: string[] = []
  // HTTP requests, and WebSockets, which the request event does not report.
  page.on('request', (r) => requests.push(r.url()))
  page.on('websocket', (ws) => requests.push(ws.url()))
  try {
    // First run: a small folder, opened, then a 300-file folder.
    const first = new Server()
    servers.push(first)
    await first.ready()
    let h = await Harness.open(page, BASE)

    const smallID = (await h.addFolder(small)).id
    expect(await h.waitIdle()).toBe(true)
    const view = await h.call<FolderView>('Catalog', 'Open', smallID)
    expect(await h.waitIdle()).toBe(true)
    const member = view.clusters[0].members[0]

    // Add both big folders, wait until both jobs have made progress, pick
    // in the small folder and read the big folders' states, all inside the
    // page (no round trip through the test runner): the synthetic photos
    // scan in well under a second, and the signal must land while both run.
    const mid = await page.evaluate(
      async ({ bigs, smallID, fileID }) => {
        const c = window.choix
        const added = await Promise.all(bigs.map((b) => c.TestSupport.AddFolderPath(b)))
        const ids = added.map((a) => a.id)
        const deadline = Date.now() + 60_000
        for (;;) {
          const list = await c.Library.List()
          const fs = ids.map((id) => list.find((x) => x.id === id))
          if (fs.every((f) => f?.state === 'scanning' && (f.scan?.done ?? 0) > 0)) {
            break
          }
          if (Date.now() > deadline) {
            throw new Error(`the big folders never reported progress together (states ${fs.map((f) => f?.state).join(', ')})`)
          }
        }
        const pick = await c.Catalog.SetPick(smallID, fileID, 'pick')
        const list = await c.Library.List()
        return {
          ids,
          pick: { state: pick.state, exported_path: pick.exported_path },
          states: ids.map((id) => list.find((x) => x.id === id)?.state),
        }
      },
      { bigs: [big, big2], smallID, fileID: member.file_id },
    )
    const signalled = Date.now()
    first.proc.kill('SIGTERM')
    const [bigID, big2ID] = mid.ids
    const pick: PickResult = { file_id: member.file_id, ...mid.pick }
    expect(pick.state).toBe('picked')
    expect(mid.states, 'both big folders were still scanning after the pick').toEqual(['scanning', 'scanning'])

    const exit = await Promise.race([
      first.exited,
      new Promise<'timeout'>((r) => setTimeout(() => r('timeout'), 8_000)),
    ])
    expect(exit, `exit within 8 s; output:\n${first.output()}`).not.toBe('timeout')
    expect(Date.now() - signalled).toBeLessThanOrEqual(8_000)
    expect(exit).toEqual({ code: 0, signal: null })

    // The signal must have interrupted both scans: with the process gone,
    // the persisted state still holds each big folder's job and files that
    // have not reached `analyzed`. Otherwise the restart below proves
    // nothing.
    const atSignal = persisted(bigID, big)
    const atSignal2 = persisted(big2ID, big2)
    test.info().annotations.push({ type: 'pending at the signal', description: JSON.stringify([atSignal, atSignal2]) })
    console.log(`quit: persisted at the signal ${JSON.stringify([atSignal, atSignal2])}`)
    for (const s of [atSignal, atSignal2]) {
      expect(
        s.jobPending === 1 && s.unfinished > 0,
        `a scan finished before the signal; nothing was interrupted (${JSON.stringify(s)})`,
      ).toBe(true)
    }

    // Second run on the same data directory.
    const second = new Server()
    servers.push(second)
    await second.ready()
    h = await Harness.open(page, BASE)

    expect((await h.list()).map((f) => f.id).sort()).toEqual([bigID, big2ID, smallID].sort())
    expect(await h.waitIdle(180_000)).toBe(true)
    expect(await h.folder(bigID)).toMatchObject({ state: 'ready', photos: BIG_COUNT })
    expect(await h.folder(big2ID)).toMatchObject({ state: 'ready', photos: BIG_COUNT })

    const reopened = await h.call<FolderView>('Catalog', 'Open', smallID)
    const again = reopened.clusters.flatMap((c) => c.members).find((m) => m.file_id === member.file_id)
    expect(again?.picked).toBe(true)
    expect(pick.exported_path).toBeTruthy()
    const copy = join(small, pick.exported_path!)
    expect(existsSync(copy)).toBe(true)
    expect(readFileSync(copy).equals(readFileSync(join(small, member.path)))).toBe(true)
    expect(await h.waitIdle()).toBe(true)
    expect(hostsAway(requests, PORT), `requests and WebSockets not to 127.0.0.1:${PORT}`).toEqual([])

    // Stop the second run cleanly, then check that the interrupted work was
    // finished: in each big folder every one of the 300 files has one row,
    // analyzed, and the folder's job marker is cleared.
    second.proc.kill('SIGTERM')
    const secondExit = await Promise.race([
      second.exited,
      new Promise<'timeout'>((r) => setTimeout(() => r('timeout'), 8_000)),
    ])
    expect(secondExit, `second run exits within 8 s; output:\n${second.output()}`).toEqual({ code: 0, signal: null })
    for (const [id, root, at] of [
      [bigID, big, atSignal],
      [big2ID, big2, atSignal2],
    ] as const) {
      expect(persisted(id, root), `after the restart (at the signal: ${JSON.stringify(at)})`).toEqual({
        jobPending: 0,
        jobKind: '',
        rows: BIG_COUNT,
        unfinished: 0,
        statuses: { analyzed: BIG_COUNT },
      })
    }
  } finally {
    await page.close()
    for (const s of servers) {
      await s.kill()
    }
  }
})
