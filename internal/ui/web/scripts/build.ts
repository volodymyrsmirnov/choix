// Build the choix SPA into ./dist with hashed filenames and an index.html
// that references them. Run with `bun run build`.
//
// Output:
//   dist/icon.<hash>.svg — app icon (favicon + AppBar mark)
//   dist/main.<hash>.js
//   dist/main.<hash>.css
//   dist/index.html  — references the hashed asset paths under /static/
//
// The hash is the first 8 hex chars of the SHA-256 of the bundle content.
// That way the embedded binary serves a fresh URL on every release and
// the browser cache for old URLs is irrelevant.

import { $ } from 'bun'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const DIST = join(ROOT, 'dist')

function hash8(buf: Uint8Array | string): string {
  return createHash('sha256').update(buf).digest('hex').slice(0, 8)
}

// 1. Reset dist.
rmSync(DIST, { recursive: true, force: true })
mkdirSync(DIST, { recursive: true })

// 2. App icon. The source lives with the rest of the icon set in
//    assets/icon/ (generated by `make icons`); the SPA uses the variant
//    drawn for small sizes, as both the favicon and the AppBar mark. It is
//    hashed first so the JS bundle can be told its URL.
const iconBuf = readFileSync(join(ROOT, '../../../assets/icon/favicon.svg'))
const iconName = `icon.${hash8(iconBuf)}.svg`
writeFileSync(join(DIST, iconName), iconBuf)

// 3. JS bundle. Bun's `--entry-naming` only takes a literal name, so we
//    bundle to a stable name first, hash, then rename.
//    `--production` sets NODE_ENV=production for both React and bun's JSX
//    transform; defining process.env.NODE_ENV alone would swap React to its
//    production runtime while the transform still emits jsxDEV calls.
//    `--define` must be `--define KEY=VALUE` (space-separated): bun silently
//    ignores the `--define:KEY=VALUE` form.
await $`bun build ./src/main.tsx --outdir ./dist --production --target=browser --define __CHOIX_ICON__=${JSON.stringify(`/static/${iconName}`)} --entry-naming=main.js`.cwd(ROOT)
const bundled = readFileSync(join(DIST, 'main.js'), 'utf8')
if (bundled.includes('__CHOIX_ICON__') || bundled.includes('jsx-dev-runtime')) {
  throw new Error('bun build ignored a define or emitted dev JSX (found __CHOIX_ICON__ or jsx-dev-runtime)')
}
const jsBuf = readFileSync(join(DIST, 'main.js'))
const jsHash = hash8(jsBuf)
const jsName = `main.${jsHash}.js`
writeFileSync(join(DIST, jsName), jsBuf)
rmSync(join(DIST, 'main.js'))

// 4. CSS. Same trick — emit to a stable name, hash, rename.
await $`bunx --bun tailwindcss -c ./tailwind.config.js -i ./src/styles.css -o ./dist/main.css --minify`.cwd(ROOT)
const cssBuf = readFileSync(join(DIST, 'main.css'))
const cssHash = hash8(cssBuf)
const cssName = `main.${cssHash}.css`
writeFileSync(join(DIST, cssName), cssBuf)
rmSync(join(DIST, 'main.css'))

// 5. index.html — substitute the asset references.
const html = readFileSync(join(ROOT, 'index.html'), 'utf8')
  .replace(/\/static\/icon\.svg/g, `/static/${iconName}`)
  .replace(/\/static\/main\.css/g, `/static/${cssName}`)
  .replace(/\/static\/main\.js/g, `/static/${jsName}`)
writeFileSync(join(DIST, 'index.html'), html)

console.log(`built dist/`)
for (const name of readdirSync(DIST).sort()) {
  console.log(`  ${name}`)
}
